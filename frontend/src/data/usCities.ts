/** Common nicknames / shorthand that should hit the curated list. */
const QUERY_ALIASES: Record<string, string> = {
  nyc: "new york",
  "new york city": "new york",
  la: "los angeles",
  "l.a.": "los angeles",
  sf: "san francisco",
  "san fran": "san francisco",
  philly: "philadelphia",
  vegas: "las vegas",
  "dc": "washington, district of columbia",
  "d.c.": "washington, district of columbia",
  "washington dc": "washington, district of columbia",
  "washington d.c.": "washington, district of columbia",
  "st louis": "saint louis",
  "st. louis": "saint louis",
  "st paul": "saint paul",
  "st. paul": "saint paul",
};

function toSuggestion([city, state, latitude, longitude]: CityRow): LocationSuggestion {
  return {
    displayName: `${city}, ${state}, USA`,
    latitude,
    longitude,
  };
}

function compareDisplayName(a: LocationSuggestion, b: LocationSuggestion): number {
  return a.displayName.localeCompare(b.displayName, "en", { sensitivity: "base" });
}

/** Alphabetical catalog used for local-first autocomplete. */
export const US_CITIES: LocationSuggestion[] = CITY_ROWS.map(toSuggestion).sort(compareDisplayName);

export function resolveLocationQueryAlias(query: string): string {
  const normalized = query.trim().replace(/\s+/g, " ").toLowerCase();
  return QUERY_ALIASES[normalized] ?? normalized;
}

export function filterUsCities(query: string): LocationSuggestion[] {
  const normalized = resolveLocationQueryAlias(query);
  if (!normalized) {
    return US_CITIES;
  }

  const startsWith: LocationSuggestion[] = [];
  const contains: LocationSuggestion[] = [];

  for (const city of US_CITIES) {
    const haystack = city.displayName.toLowerCase();
    const cityName = haystack.split(",")[0] ?? haystack;

    if (cityName.startsWith(normalized) || haystack.startsWith(normalized)) {
      startsWith.push(city);
    } else if (haystack.includes(normalized) || cityName.includes(normalized)) {
      contains.push(city);
    }
  }

  return [...startsWith, ...contains];
}
